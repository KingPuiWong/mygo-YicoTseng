#!/usr/bin/env python3
"""Refresh a curated catalog from the artist's actual Bilibili uploads.

The generated array is committed in index.js; installing the plugin needs no
build step, filesystem access, Node imports, account, or extra API service.
"""
import datetime
import json
from pathlib import Path
import re
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
OWNER = 472832454
HEADERS = {"User-Agent": "Mozilla/5.0", "Referer": "https://www.bilibili.com/"}
GROUPS = [
    ("newyear-2022", "New Year Live 2022 (Official)", "Official New Year Live 2022", "BV11F411J7kL"),
    ("rerecorded-2022", "Studio Re-recordings 2022 (Official)", "Official Studio Re-recording 2022", "BV1oN4y1V71W"),
]
CANDLE = [
    "BV1jB4y1u7N5", "BV1LK4y1R7Mv", "BV1Xf4y1b7NB", "BV1vB4y1K76s",
    "BV1w54y177DE", "BV1iL4y1a74v", "BV1TM4y1G7nr", "BV13f4y1n7tF",
    "BV1q341117Cp", "BV1BU4y1F7ww", "BV1ZP4y1L7t7", "BV1gq4y1g7sh", "BV1Bu411d7Ra",
]

def view(bvid):
    request = urllib.request.Request("https://api.bilibili.com/x/web-interface/view?bvid=" + bvid, headers=HEADERS)
    with urllib.request.urlopen(request, timeout=15) as response:
        body = json.load(response)
    if body.get("code") != 0 or body.get("data", {}).get("owner", {}).get("mid") != OWNER:
        raise RuntimeError(f"Cannot verify an official upload: {bvid}")
    return body["data"]

records = []

def add(bvid, group, album, label, position):
    value = view(bvid)
    names = re.findall(r"《(.*?)》", value["title"])
    if group == "rerecorded-2022":
        names = names[1:]  # The first bracketed title is the album 《2022》.
    if not names:
        raise RuntimeError(f"Cannot identify a song title: {value['title']}")
    records.append({
        "bvid": bvid, "cid": value["cid"], "song": " / ".join(names), "title": value["title"],
        "group": group, "album": album, "label": label, "duration": value["duration"] * 1000,
        "imageUrl": value["pic"].replace("http://", "https://"),
        "published": datetime.datetime.fromtimestamp(value["pubdate"], datetime.timezone.utc).date().isoformat(),
        "position": position, "uploader": OWNER,
    })
    print(bvid, records[-1]["song"], flush=True)

for group, album, label, seed in GROUPS:
    episodes = [episode for section in view(seed)["ugc_season"]["sections"] for episode in section["episodes"] if "全程回顾" not in episode["title"]]
    ids = list(dict.fromkeys(episode["bvid"] for episode in episodes))
    if group == "rerecorded-2022" and "BV1ce4y1Q7Vw" not in ids:
        ids.append("BV1ce4y1Q7Vw")  # Artist's separately published fifteenth track.
    for position, bvid in enumerate(ids, 1):
        add(bvid, group, album, label, position)
for position, bvid in enumerate(CANDLE, 1):
    add(bvid, "candle-live", "Candle Live Selections (Official)", "Official Candle Live", position)

assert len({video["bvid"] for video in records}) == len(records)
(ROOT / "official-videos.json").write_text(json.dumps(records, ensure_ascii=False, indent=2) + "\n")
entry = ROOT / "index.js"
source = entry.read_text()
start = source.index("// BEGIN OFFICIAL_VIDEOS")
end = source.index("// END OFFICIAL_VIDEOS", start)
generated = "// BEGIN OFFICIAL_VIDEOS -- generated by scripts/sync-official-catalog.py\nconst OFFICIAL_VIDEOS = " + json.dumps(records, ensure_ascii=False, separators=(",", ":")) + ";\n"
entry.write_text(source[:start] + generated + source[end:])
print(f"Updated {len(records)} verified official uploads.")
